#!/usr/bin/env node
// Local-only staff authority preparation. This tool never generates or selects a
// permanent actor/subject/policy identity, opens a socket, reads a database
// credential, changes Supabase, exports Render configuration or deploys anything.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const project = 'bljskfhazmnzmhkbkcev';
const issuer = `https://${project}.supabase.co/auth/v1`;
const directoryPath = '.local/staff-authority';
const preparationPath = `${directoryPath}/preparation.json`;
const decisionsPath = `${directoryPath}/decisions.json`;
const failure = 'Staff authority preparation refused or incomplete. Existing files were not overwritten. No credential was read and no network, database, configuration or deployment action occurred.';
const need = value => { if (!value) throw Error(failure); };
const exact = (value, keys) => value && typeof value === 'object' && !Array.isArray(value) &&
  JSON.stringify(Object.keys(value).sort()) === JSON.stringify([...keys].sort());
const canonicalUuid = value => typeof value === 'string' &&
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value);
const clean = (value, maximum) => typeof value === 'string' && value.length >= 1 && value.length <= maximum &&
  value.trim() === value && !/[\x00-\x1f\x7f-\x9f]/u.test(value);

export function staffAuthorityPreparationOperation(args) {
  need(Array.isArray(args) && args.length === 1 && ['--prepare','--check-decisions'].includes(args[0]));
  return args[0];
}

export function staffAuthorityPreparation() {
  return {
    kind:'feedme-staff-authority-preparation',formatVersion:1,runnable:false,
    status:'OWNER_DECISIONS_REQUIRED',project,environment:'production',
    fixedProvider:{issuer,audience:'authenticated',requiredAssuranceLevel:'aal2',requiredMfaMethod:'totp'},
    requiredHostedMigrations:[40,77,90],
    decisionsFile:decisionsPath,
    requiredDecisions:{
      policyVersion:null,policyClientId:null,actorId:null,subject:null,
      canPublish:null,canReview:null,moderatorEnabled:null,
      tokenValidAfter:null,notBefore:null,validUntil:null,
      maximumTotpAgeSeconds:null,observationSeconds:null,maxResponseBytes:null,
      catalogDraftsEnabled:null,catalogReviewsEnabled:null,catalogPublicationEnabled:null,
    },
    constraints:[
      'subject must be the exact Supabase auth user UUID observed after the owner completes Google sign-in; email text is not a subject identifier',
      'actorId is a permanent owner-managed UUID and is never generated by this tool',
      'policyVersion and policyClientId are permanent registry bindings selected explicitly by the operator',
      'moderation requires current aal2 plus a verified TOTP factor and does not follow from ordinary app login',
      'catalog review requires catalog drafts; catalog publication requires catalog review',
      'the decisions file is owner-only local input and must not contain passwords, tokens, signing keys or database credentials',
    ],
    activationOrder:['apply-v089-v090-and-reviewed-serving-grants','install-owner-approved-policy-actor-and-moderator-enrollment',
      'create-reviewed-private-runtime-configuration','configure-render-without-logging-secrets','deploy-and-complete-live-staff-acceptance'],
    limitations:['Preparation and decision validation only','No permanent identity selected','No SQL generated or applied',
      'No runtime configuration exported','No Render or Play action'],
  };
}

function canonicalInstant(value) {
  need(typeof value === 'string' && /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{3})?Z$/.test(value));
  const millis = Date.parse(value);
  need(Number.isFinite(millis) && new Date(millis).toISOString() ===
    (value.includes('.') ? value : value.replace('Z','.000Z')));
  return millis;
}

export function validateStaffAuthorityDecisions(raw) {
  try {
    need(typeof raw === 'string' && Buffer.byteLength(raw) > 0 && Buffer.byteLength(raw) <= 32768);
    const value = JSON.parse(raw);
    let compact='', quoted=false, escaped=false;
    for (const character of raw) {
      if (quoted || !/\s/.test(character)) compact += character;
      if (escaped) escaped=false;
      else if (quoted && character === '\\') escaped=true;
      else if (character === '"') quoted=!quoted;
    }
    need(compact === JSON.stringify(value));
    need(exact(value,['formatVersion','project','environment','issuer','audience','policyVersion','policyClientId',
      'actorId','subject','canPublish','canReview','moderatorEnabled','tokenValidAfter','notBefore','validUntil',
      'maximumTotpAgeSeconds','observationSeconds','maxResponseBytes','catalogDraftsEnabled','catalogReviewsEnabled',
      'catalogPublicationEnabled']));
    need(value.formatVersion === 1 && value.project === project && value.environment === 'production' &&
      value.issuer === issuer && value.audience === 'authenticated');
    need(clean(value.policyVersion,128) && clean(value.policyClientId,256) && canonicalUuid(value.actorId) &&
      canonicalUuid(value.subject));
    for (const field of ['canPublish','canReview','moderatorEnabled','catalogDraftsEnabled','catalogReviewsEnabled',
      'catalogPublicationEnabled']) need(typeof value[field] === 'boolean');
    need(value.moderatorEnabled === true);
    need(!value.catalogReviewsEnabled || value.catalogDraftsEnabled);
    need(!value.catalogPublicationEnabled || value.catalogReviewsEnabled);
    need(Number.isInteger(value.maximumTotpAgeSeconds) && value.maximumTotpAgeSeconds >= 1 && value.maximumTotpAgeSeconds <= 900);
    need(Number.isInteger(value.observationSeconds) && value.observationSeconds >= 1 &&
      value.observationSeconds <= 60 && value.observationSeconds <= value.maximumTotpAgeSeconds);
    need(Number.isInteger(value.maxResponseBytes) && value.maxResponseBytes >= 1024 && value.maxResponseBytes <= 16384);
    const token = canonicalInstant(value.tokenValidAfter), from = canonicalInstant(value.notBefore), until = canonicalInstant(value.validUntil);
    need(from < until && token < until);
    return {status:'staff-authority-decisions-valid-local',project,environment:'production',
      catalogDraftsEnabled:value.catalogDraftsEnabled,catalogReviewsEnabled:value.catalogReviewsEnabled,
      catalogPublicationEnabled:value.catalogPublicationEnabled,moderatorEnabled:true,
      canPublish:value.canPublish,canReview:value.canReview,notBefore:value.notBefore,validUntil:value.validUntil,
      credentialRead:false,connected:false,changed:false};
  } catch { throw Error(failure); }
}

function secureDirectory() {
  need(typeof process.getuid === 'function');
  let current = root;
  for (const part of ['.local','staff-authority']) {
    current = path.join(current,part);
    try { fs.mkdirSync(current,{mode:0o700}); } catch (error) { if (error.code !== 'EEXIST') throw error; }
    const stat = fs.lstatSync(current);
    need(stat.isDirectory() && !stat.isSymbolicLink() && fs.realpathSync(current) === current &&
      stat.uid === process.getuid() && (stat.mode & 0o777) === 0o700);
  }
  return current;
}

function readPrivate(file) {
  const before = fs.lstatSync(file);
  need(before.isFile() && !before.isSymbolicLink() && before.nlink === 1 && before.uid === process.getuid() &&
    (before.mode & 0o777) === 0o600 && before.size > 0 && before.size <= 32768);
  const fd = fs.openSync(file,fs.constants.O_RDONLY|fs.constants.O_NOFOLLOW|fs.constants.O_NONBLOCK);
  let bytes;
  try {
    const opened = fs.fstatSync(fd); need(opened.ino === before.ino && opened.dev === before.dev && opened.size === before.size);
    bytes = Buffer.alloc(opened.size + 1); let count = 0;
    while (count < bytes.length) { const read = fs.readSync(fd,bytes,count,bytes.length-count,null); if (!read) break; count += read; }
    const after = fs.fstatSync(fd); need(count === opened.size && after.size === opened.size &&
      after.mtimeMs === opened.mtimeMs && after.ctimeMs === opened.ctimeMs);
    return Buffer.from(bytes.subarray(0,count));
  } finally { bytes?.fill(0); fs.closeSync(fd); }
}

function writePreparation() {
  const directory = secureDirectory(), file = path.join(directory,'preparation.json');
  const bytes = Buffer.from(JSON.stringify(staffAuthorityPreparation(),null,2)+'\n');
  try {
    let existing;
    try { existing = readPrivate(file); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (existing) { try { need(existing.equals(bytes)); return {status:'existing-staff-authority-preparation-preserved',
      path:preparationPath,runnable:false}; } finally { existing.fill(0); } }
    const fd = fs.openSync(file,fs.constants.O_WRONLY|fs.constants.O_CREAT|fs.constants.O_EXCL|fs.constants.O_NOFOLLOW,0o600);
    try { fs.fchmodSync(fd,0o600); fs.writeFileSync(fd,bytes); fs.fsyncSync(fd); }
    finally { fs.closeSync(fd); }
    const stored = readPrivate(file); try { need(stored.equals(bytes)); } finally { stored.fill(0); }
    return {status:'staff-authority-preparation-created',path:preparationPath,runnable:false};
  } finally { bytes.fill(0); }
}

function checkDecisions() {
  const directory = secureDirectory(), bytes = readPrivate(path.join(directory,'decisions.json'));
  try { return validateStaffAuthorityDecisions(new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(bytes)); }
  finally { bytes.fill(0); }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const operation = staffAuthorityPreparationOperation(process.argv.slice(2));
    console.log(JSON.stringify(operation === '--prepare' ? writePreparation() : checkDecisions()));
  } catch { console.error(failure+' Use --prepare or --check-decisions only.'); process.exitCode = 1; }
}
